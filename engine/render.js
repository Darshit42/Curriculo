/** Render the course manifest to a committable, GitHub-readable LEARN.md. */

const LETTERS = 'ABCDE';

function fileLink(p) {
  return `[\`${p}\`](${p.split('/').map(encodeURIComponent).join('/')})`;
}

function escapeHtml(s) {
  return s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

export function renderLearnMd(course) {
  const out = [];
  const date = course.generatedAt.slice(0, 10);
  out.push(`# Learn ${course.repo.split('/').pop()}`);
  out.push('');
  out.push(
    `> A guided course through \`${course.repo}\`: ${course.lessons.length} lessons, ordered from entry points to the parts that trip people up, each tied to real files and followed by a short quiz.`,
  );
  out.push(`> Generated by [Curriculo](https://github.com/Darshit42/Curriculo) on ${date}. Take it interactively with \`npx curriculo learn\`.`);
  out.push('');
  out.push('## Orientation');
  out.push('');
  out.push(course.summary);
  out.push('');
  out.push('## Course map');
  out.push('');
  for (const l of course.lessons) {
    out.push(`${l.order}. [${l.title}](#lesson-${l.order}) — ${l.files.map((f) => `\`${f}\``).join(', ')}`);
  }
  out.push('');

  for (const l of course.lessons) {
    out.push('---');
    out.push('');
    out.push(`<a id="lesson-${l.order}"></a>`);
    out.push('');
    out.push(`## ${l.order}. ${l.title}`);
    out.push('');
    out.push(`**Files:** ${l.files.map(fileLink).join(' · ')}`);
    out.push('');
    out.push(l.body.trim());
    out.push('');
    if (l.quiz?.length) {
      out.push('<details>');
      out.push(`<summary><strong>Check yourself</strong> (${l.quiz.length} question${l.quiz.length === 1 ? '' : 's'})</summary>`);
      out.push('');
      l.quiz.forEach((q, qi) => {
        out.push(`**Q${qi + 1}. ${q.q}**`);
        out.push('');
        q.choices.forEach((c, ci) => out.push(`- ${LETTERS[ci]}. ${c}`));
        out.push('');
        out.push(`<details><summary>Answer</summary>`);
        out.push('');
        out.push(`**${LETTERS[q.answer]}** — ${escapeHtml(q.why)}`);
        out.push('');
        out.push('</details>');
        out.push('');
      });
      out.push('</details>');
      out.push('');
    }
  }
  out.push('---');
  out.push('');
  out.push(`<sub>Regenerate after a refactor with \`npx curriculo gen .\` — model: ${course.model}.</sub>`);
  out.push('');
  return out.join('\n');
}

/** Markdown badge a maintainer can paste into their README. */
export function badgeMarkdown() {
  return '[![Course: LEARN.md](https://img.shields.io/badge/onboarding-LEARN.md-4c6ef5?logo=bookstack&logoColor=white)](LEARN.md)';
}
